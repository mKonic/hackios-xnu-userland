#!/usr/bin/env python3
"""Make the C encoders of gfxstream's renderControl and GLES 2/3 wire protocols from gfxstream's
own descriptions (codegen/{gles2,renderControl}/*.{in,attrib,types} of google/gfxstream, Apache-2.0;
tools/gfxstream/fetch.sh gets them at a pinned commit, nothing of them is in this repository).

  mkgfxenc.py CODEGEN_DIR OUT.h OUT.c OUT_API.c [OPCODES.h ...]

For every entry this writes gfxe_<name>(struct gfx *c, args...), which encodes the call the way
gfxstream's generated guest encoders (emugen) do, so the host's decoders read it:

  [opcode u32][packet size u32] then each argument in order:
    scalar            its bytes (the .types file gives the width: 8, 16, 32 or 64 bits)
    pointer, dir in   [u32 byte count][the bytes]       (count from the .attrib 'len' expression)
    pointer, dir out  [u32 byte count]                   (the host writes that many bytes back)
    pointer, inout    [u32 byte count][the bytes]
  and the replies come back in order: every out/inout buffer, then the return value.

Pointers on the wire are never addresses. Entries the .attrib marks 'unsupported', and those
with a pointer and no 'len', are not made (the hand-written layer, gfx_gl.c, covers what
CoreAnimation needs of those). With OPCODES.h files (gfxstream's guest/*_opcodes.h) the
opcodes are checked against gfxstream's own.
"""
import re
import sys

codegen, out_h, out_c, out_api = sys.argv[1:5]
check_files = sys.argv[5:]


def parse_types(path):
    sizes = {}
    for line in open(path):
        f = line.split()
        if len(f) >= 2 and not line.startswith('#'):
            sizes[f[0]] = int(f[1])
    return sizes


def parse_in(path):
    entries = []
    for line in open(path):
        m = re.match(r'\s*GL_EN[TR]+Y\((.*)\)\s*;?\s*$', line)
        if not m:
            continue
        parts = [p.strip() for p in m.group(1).split(',')]
        ret, name, params = parts[0], parts[1], []
        for p in parts[2:]:
            if not p or p == 'void':
                continue
            pm = re.match(r'(.*?)([A-Za-z_][A-Za-z_0-9]*)$', p)
            ptype = re.sub(r'\s+', '', pm.group(1).replace('const', ''))
            params.append((ptype, pm.group(2)))
        entries.append((ret.replace(' ', ''), name, params))
    return entries


def parse_attrib(path):
    attrs, cur = {}, None
    for line in open(path):
        line = line.split('#')[0].rstrip()
        if not line.strip():
            continue
        if not line[0].isspace():
            cur = attrs.setdefault(line.strip(), {'dir': {}, 'len': {}, 'flags': set(), 'var_flags': {}})
            continue
        f = line.split()
        if cur is None:
            continue
        if f[0] == 'dir':
            cur['dir'][f[1]] = f[2]
        elif f[0] == 'len':
            cur['len'][f[1]] = ' '.join(f[2:])
        elif f[0] == 'flag':
            cur['flags'].add(f[1])
        elif f[0] == 'var_flag':
            cur['var_flags'].setdefault(f[1], set()).update(f[2:])
        elif f[0] == 'base_opcode':
            cur['base'] = int(f[1])
    return attrs


def ctype(t):
    base = t.rstrip('*')
    star = t[len(base):]
    m = {'GLvoid': 'void', 'RenderControlByte': 'uint8_t', 'GLstr': 'char', 'GLvoidptr': 'void*'}
    return m.get(base, base) + star


def cexpr(e):
    e = e.replace('glesv2_enc::pixelDataSize(self,', 'gfx_pixel_size(c,')
    e = e.replace('glesv2_enc::', 'gfx_').replace('glUtilsParamSize', 'gfx_param_size')
    e = e.replace('glUtilsPixelBitSize', 'gfx_pixel_bits').replace('glSizeof', 'gfx_sizeof')
    e = re.sub(r'\bself\b', 'c', e)
    return e


def width(sizes, t):
    if '*' in t:
        return 4
    return sizes.get(t, 32) // 8


hdr = ['/* generated by tools/gfxstream/mkgfxenc.py from google/gfxstream codegen (Apache-2.0) */',
       '#pragma once', '#include "gfx.h"', '']
src = ['/* generated by tools/gfxstream/mkgfxenc.py from google/gfxstream codegen (Apache-2.0) */',
       '#include <string.h>', '#include "gfx_enc.h"', '']
api_src = ['/* generated by tools/gfxstream/mkgfxenc.py: the gl* entry points that need no client state.',
           ' * Weak: src/gfx/gfx_gl.c defines the ones that do, and those win. */',
           '#include "gfx_enc.h"', '']
opcodes = {}
made = skipped = 0
for api, base_name in (('gles2', 'gles2'), ('renderControl', 'renderControl')):
    sizes = parse_types(f'{codegen}/{api}/{base_name}.types')
    entries = parse_in(f'{codegen}/{api}/{base_name}.in')
    attrs = parse_attrib(f'{codegen}/{api}/{base_name}.attrib')
    base = attrs.get('GLOBAL', {}).get('base', 2048 if api == 'gles2' else 10000)
    for i, (ret, name, params) in enumerate(entries):
        op = base + i
        opcodes[name] = op
        hdr.append(f'#define GFXOP_{name} {op}')
        a = attrs.get(name, {'dir': {}, 'len': {}, 'flags': set(), 'var_flags': {}})
        if 'unsupported' in a['flags']:
            skipped += 1
            continue
        if any('*' in t and n not in a['len'] for t, n in params) or \
                any('*' not in t and t not in sizes for t, n in params):
            skipped += 1
            continue

        def decl(t, n):
            const = 'const ' if '*' in t and a['dir'].get(n, 'in') == 'in' else ''
            return f'{const}{ctype(t)} {n}'
        args = ''.join(f', {decl(t, n)}' for t, n in params)
        rtype = ctype(ret) if ret != 'void' else 'void'
        hdr.append(f'{rtype} gfxe_{name}(struct gfx *c{args});')
        body = []
        fixed = 8
        sized = []
        for t, n in params:
            if '*' in t:
                d = a['dir'].get(n, 'in')
                null_ok = 'nullAllowed' in a['var_flags'].get(n, set())
                lenx = cexpr(a['len'][n])
                body.append(f'\tconst uint32_t __size_{n} = ' +
                            (f'({n} != NULL) ? (uint32_t)({lenx}) : 0;' if null_ok else f'(uint32_t)({lenx});'))
                fixed += 4
                if d in ('in', 'inout'):
                    sized.append(f'__size_{n}')
            else:
                fixed += width(sizes, t)
        total = ' + '.join([str(fixed)] + sized)
        body.append(f'\tconst uint32_t __total = {total};')
        body.append(f'\tuint8_t *p = gfx_begin(c, {op}, __total);')
        body.append('\tif (p == NULL) {')
        body.append('\t\t' + ('return 0;' if rtype != 'void' else 'return;'))
        body.append('\t}')
        for t, n in params:
            if '*' in t:
                d = a['dir'].get(n, 'in')
                body.append(f'\tmemcpy(p, &__size_{n}, 4); p += 4;')
                if d in ('in', 'inout'):
                    body.append(f'\tif (__size_{n}) {{ memcpy(p, {n}, __size_{n}); p += __size_{n}; }}')
            else:
                w = width(sizes, t)
                body.append(f'\tmemcpy(p, &{n}, {w}); p += {w};')
        body.append('\t(void)p;')
        outs = [(t, n) for t, n in params if '*' in t and a['dir'].get(n, 'in') in ('out', 'inout')]
        for t, n in outs:
            body.append(f'\tif (__size_{n}) gfx_read(c, {n}, __size_{n});')
        if rtype != 'void':
            w = width(sizes, ret)
            body.append(f'\t{rtype} __ret = 0;')
            body.append(f'\tgfx_read(c, &__ret, {w});')
            body.append('\treturn __ret;')
        src.append(f'{rtype}\ngfxe_{name}(struct gfx *c{args})\n{{')
        src += body
        src.append('}\n')
        made += 1
        if api == 'gles2' and 'not_api' not in a['flags']:
            names = ', '.join(n for _, n in params)
            call = f'gfxe_{name}(gfx_current(){", " if names else ""}{names})'
            api_src.append(f'__attribute__((weak, visibility("default"))) {rtype}\n{name}({args[2:] or "void"})\n{{')
            api_src.append(f'\t{"return " if rtype != "void" else ""}{call};\n}}\n')

for path in check_files:
    for line in open(path):
        m = re.match(r'#define OP_(\w+)\s+(\d+)', line)
        if m and m.group(1) in opcodes and opcodes[m.group(1)] != int(m.group(2)):
            sys.exit(f'mkgfxenc.py: opcode of {m.group(1)} is {opcodes[m.group(1)]}, gfxstream says {m.group(2)}')

open(out_h, 'w').write('\n'.join(hdr) + '\n')
open(out_c, 'w').write('\n'.join(src) + '\n')
open(out_api, 'w').write('\n'.join(api_src) + '\n')
print(f'mkgfxenc.py: {made} encoders, {skipped} entries left to the hand-written layer', file=sys.stderr)
